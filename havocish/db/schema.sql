CREATE INDEX IF NOT EXISTS character_images_guild_idx ON public.character_images (discord_guild_id);

-- ─── ai_packs ────────────────────────────────────────────────────────────────
-- Worlds made with the AI builder, one row per generation. See
-- migrations/006_ai_packs.sql.

CREATE TABLE IF NOT EXISTS public.ai_packs (
    id               UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    discord_guild_id BIGINT      NOT NULL,
    prompt           TEXT        NOT NULL,
    pack             JSONB       NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ai_packs_guild_idx ON public.ai_packs (discord_guild_id);

-- ─── ai_usage ────────────────────────────────────────────────────────────────
-- One row per AI model call, with its tokens: cost per server, and the
-- helper's daily cap. See migrations/007_ai_usage.sql.

CREATE TABLE IF NOT EXISTS public.ai_usage (
    id               BIGSERIAL   PRIMARY KEY,
    discord_guild_id BIGINT      NOT NULL,
    kind             TEXT        NOT NULL,
    model            TEXT        NOT NULL,
    input_tokens     INTEGER     NOT NULL,
    output_tokens    INTEGER     NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ai_usage_guild_idx ON public.ai_usage (discord_guild_id, created_at);

-- ─── ai_limits ───────────────────────────────────────────────────────────────
-- One server's AI allowance, over the defaults (null = default). See
-- migrations/008_ai_limits.sql.

CREATE TABLE IF NOT EXISTS public.ai_limits (
    discord_guild_id BIGINT      PRIMARY KEY,
    helper_daily     INTEGER,
    packs            INTEGER,
    note             TEXT,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ─── daily_overrides ─────────────────────────────────────────────────────────
-- An admin's changes to one day of the website's Daily. See
-- migrations/009_daily_overrides.sql.

CREATE TABLE IF NOT EXISTS public.daily_overrides (
    day        INTEGER     PRIMARY KEY,
    override   JSONB       NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ─── command_uses ────────────────────────────────────────────────────────────
-- Slash command use counts per server and day, for /admin. See
-- migrations/010_command_uses.sql.

CREATE TABLE IF NOT EXISTS public.command_uses (
    discord_guild_id BIGINT  NOT NULL,
    command          TEXT    NOT NULL,
    day              DATE    NOT NULL DEFAULT CURRENT_DATE,
    uses             INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (discord_guild_id, command, day)
);

-- ─── daily_plays ─────────────────────────────────────────────────────────────
-- How many played each day of the website's Daily and how their runs ended:
-- anonymous counts, no players stored. See migrations/011_daily_plays.sql.

CREATE TABLE IF NOT EXISTS public.daily_plays (
    day        INTEGER     PRIMARY KEY,
    players    INTEGER     NOT NULL DEFAULT 0,
    wins       INTEGER     NOT NULL DEFAULT 0,
    timeouts   INTEGER     NOT NULL DEFAULT 0,
    falls      INTEGER     NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- ─── guild_log ───────────────────────────────────────────────────────────────
-- Every time the bot joins, leaves or rejoins a server (guilds keeps only the
-- latest removal). Written by the track_guild trigger below. See
-- migrations/012_server_history.sql.

CREATE TABLE IF NOT EXISTS public.guild_log (
    discord_guild_id BIGINT      NOT NULL,
    event            TEXT        NOT NULL,   -- joined | left | rejoined
    at               TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_guild_log_guild ON public.guild_log (discord_guild_id, at);

-- ─── config_history ──────────────────────────────────────────────────────────
-- Each saved version of a server's config, whatever saved it (the dashboard,
-- /config, /setup, the AI builder). /admin's server page compares consecutive
-- versions to say what changed. The latest 50 per server are kept.

CREATE TABLE IF NOT EXISTS public.config_history (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discord_guild_id BIGINT      NOT NULL,
    config           JSONB       NOT NULL,
    at               TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_config_history_guild ON public.config_history (discord_guild_id, id DESC);

CREATE OR REPLACE FUNCTION public.track_guild() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.guild_log (discord_guild_id, event) VALUES (NEW.discord_guild_id, 'joined');
        RETURN NEW;
    END IF;
    IF OLD.removed_at IS NULL AND NEW.removed_at IS NOT NULL THEN
        INSERT INTO public.guild_log (discord_guild_id, event) VALUES (NEW.discord_guild_id, 'left');
    ELSIF OLD.removed_at IS NOT NULL AND NEW.removed_at IS NULL THEN
        INSERT INTO public.guild_log (discord_guild_id, event) VALUES (NEW.discord_guild_id, 'rejoined');
    END IF;
    IF NEW.config IS DISTINCT FROM OLD.config AND NEW.config IS NOT NULL THEN
        -- The first tracked change also keeps the version before it, so it has something to compare with.
        IF OLD.config IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.config_history WHERE discord_guild_id = NEW.discord_guild_id) THEN
            INSERT INTO public.config_history (discord_guild_id, config) VALUES (NEW.discord_guild_id, OLD.config);
        END IF;
        INSERT INTO public.config_history (discord_guild_id, config) VALUES (NEW.discord_guild_id, NEW.config);
        DELETE FROM public.config_history WHERE discord_guild_id = NEW.discord_guild_id AND id <= (
            SELECT id FROM public.config_history WHERE discord_guild_id = NEW.discord_guild_id ORDER BY id DESC OFFSET 50 LIMIT 1);
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS track_guild ON public.guilds;
CREATE TRIGGER track_guild AFTER INSERT OR UPDATE ON public.guilds
    FOR EACH ROW EXECUTE FUNCTION public.track_guild();

-- ─── interaction_log ─────────────────────────────────────────────────────────
-- Every command, button, menu and form used in a server: when, by whom (and
-- whether they own or manage it), the options picked, how long it took and
-- whether it failed. For /admin's server page; kept 30 days (pruneOldEvents).
-- See migrations/013_interaction_log.sql.

CREATE TABLE IF NOT EXISTS public.interaction_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discord_guild_id BIGINT      NOT NULL,
    discord_user_id  BIGINT      NOT NULL,
    role             TEXT,                   -- owner | manager | null
    kind             TEXT        NOT NULL,   -- command | button | select | form
    name             TEXT        NOT NULL,   -- "fight", "admin give", or a button's id
    options          JSONB,
    ok               BOOLEAN     NOT NULL DEFAULT TRUE,
    ms               INTEGER,
    at               TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_interaction_log_guild ON public.interaction_log (discord_guild_id, at DESC);
CREATE INDEX IF NOT EXISTS idx_interaction_log_at ON public.interaction_log (at);

-- ─── schema_migrations ───────────────────────────────────────────────────────
-- The ledger scripts/migrate.sh keeps, so "is migration N live yet?" has an
-- answer that is not somebody's memory. One row per applied migration, keyed
-- by filename-without-.sql, with a checksum of the file as applied -- editing
-- an already-applied migration is then caught instead of silently diverging
-- from what the database actually contains.
--
-- Created here so a database built from this file starts with the ledger, and
-- again by migrate.sh so one that predates it picks the ledger up.

CREATE TABLE IF NOT EXISTS public.schema_migrations (
    version    TEXT        PRIMARY KEY,
    checksum   TEXT        NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMIT;
