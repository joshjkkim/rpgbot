CREATE TABLE IF NOT EXISTS public.starter_packs (
    id                      TEXT        PRIMARY KEY,
    name                    TEXT        NOT NULL,
    description             TEXT        NOT NULL DEFAULT '',
    source_discord_guild_id BIGINT      NOT NULL,
    position                INTEGER     NOT NULL DEFAULT 0,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW()
