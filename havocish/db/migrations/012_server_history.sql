-- 012: Server history, for the admin pages.
--
-- Logs every time the bot joins, leaves or rejoins a server, and keeps each
-- saved version of a server's config, both from a trigger on guilds so every
-- path that writes them is covered. /admin's server page builds its timeline
-- from these. Servers' earlier history isn't known: it starts when this runs.

BEGIN;

CREATE TABLE IF NOT EXISTS public.guild_log (
    discord_guild_id BIGINT      NOT NULL,
    event            TEXT        NOT NULL,   -- joined | left | rejoined
    at               TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_guild_log_guild ON public.guild_log (discord_guild_id, at);

-- ─── config_history ──────────────────────────────────────────────────────────
-- Each saved version of a server's config, whatever saved it (the dashboard,
-- /config, /setup, the AI builder). /admin's server page compares consecutive
-- versions to say what changed. The latest 50 per server are kept.

CREATE TABLE IF NOT EXISTS public.config_history (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discord_guild_id BIGINT      NOT NULL,
    config           JSONB       NOT NULL,
    at               TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_config_history_guild ON public.config_history (discord_guild_id, id DESC);

CREATE OR REPLACE FUNCTION public.track_guild() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.guild_log (discord_guild_id, event) VALUES (NEW.discord_guild_id, 'joined');
        RETURN NEW;
    END IF;
    IF OLD.removed_at IS NULL AND NEW.removed_at IS NOT NULL THEN
        INSERT INTO public.guild_log (discord_guild_id, event) VALUES (NEW.discord_guild_id, 'left');
    ELSIF OLD.removed_at IS NOT NULL AND NEW.removed_at IS NULL THEN
        INSERT INTO public.guild_log (discord_guild_id, event) VALUES (NEW.discord_guild_id, 'rejoined');
    END IF;
    IF NEW.config IS DISTINCT FROM OLD.config AND NEW.config IS NOT NULL THEN
        -- The first tracked change also keeps the version before it, so it has something to compare with.
        IF OLD.config IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.config_history WHERE discord_guild_id = NEW.discord_guild_id) THEN
            INSERT INTO public.config_history (discord_guild_id, config) VALUES (NEW.discord_guild_id, OLD.config);
        END IF;
        INSERT INTO public.config_history (discord_guild_id, config) VALUES (NEW.discord_guild_id, NEW.config);
        DELETE FROM public.config_history WHERE discord_guild_id = NEW.discord_guild_id AND id <= (
            SELECT id FROM public.config_history WHERE discord_guild_id = NEW.discord_guild_id ORDER BY id DESC OFFSET 50 LIMIT 1);
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS track_guild ON public.guilds;
CREATE TRIGGER track_guild AFTER INSERT OR UPDATE ON public.guilds
    FOR EACH ROW EXECUTE FUNCTION public.track_guild();

COMMIT;
