-- 013: Interaction log.
--
-- Every command, button, menu and form used in a server, with its exact time,
-- so /admin can show what a server does click by click (command_uses keeps
-- only a count per day). Kept 30 days.

BEGIN;

CREATE TABLE IF NOT EXISTS public.interaction_log (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discord_guild_id BIGINT      NOT NULL,
    discord_user_id  BIGINT      NOT NULL,
    role             TEXT,                   -- owner | manager | null
    kind             TEXT        NOT NULL,   -- command | button | select | form
    name             TEXT        NOT NULL,   -- "fight", "admin give", or a button's id
    options          JSONB,
    ok               BOOLEAN     NOT NULL DEFAULT TRUE,
    ms               INTEGER,
    at               TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_interaction_log_guild ON public.interaction_log (discord_guild_id, at DESC);
CREATE INDEX IF NOT EXISTS idx_interaction_log_at ON public.interaction_log (at);

COMMIT;
